#!/usr/bin/env node
// scripts/stamp-edge-release.mjs
//
// Writes the current Git SHA into `supabase/functions/_shared/release.ts` so edge
// functions can tag Sentry events + log lines with a real release identifier
// (matching what the Vite build injects into `__APP_VERSION__` on the frontend).
//
// Why a committed constant instead of a Supabase secret?
//   - Supabase secrets don't auto-sync with Lovable builds; anyone would forget to
//     bump SENTRY_RELEASE on every deploy, collapsing release-health into a single
//     bucket (the same bug we just fixed on the frontend).
//   - A Git SHA baked into a committed TS file deploys with the edges themselves.
//     Every `supabase functions deploy` carries the release alongside the code it
//     describes — no out-of-band secret syncing required.
//
// Idempotent: if the file already contains the current SHA, it exits 0 without
// writing. Safe to run from pre-push hooks.
//
// Usage:
//   node scripts/stamp-edge-release.mjs             # write/update stamp
//   node scripts/stamp-edge-release.mjs --check     # exit 1 if stamp is out of date

import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const TARGET = resolve(ROOT, "supabase/functions/_shared/release.ts");

const args = new Set(process.argv.slice(2));
const CHECK_ONLY = args.has("--check");

function currentSha() {
  try {
    return execSync("git rev-parse --short=12 HEAD", {
      cwd: ROOT,
      stdio: ["ignore", "pipe", "ignore"],
      encoding: "utf8",
      timeout: 2000,
    }).trim();
  } catch {
    return "";
  }
}

function render(sha, stampedAt) {
  // Keep this file autogenerated + committed so `supabase functions deploy`
  // ships the release identifier alongside the code. Do not edit by hand.
  return `// AUTOGENERATED by scripts/stamp-edge-release.mjs — do not edit by hand.
// Bump via: \`npm run stamp:release\` (also runs automatically in pre-push).
// Mirrors the frontend \`__APP_VERSION__\` so Sentry can correlate releases
// across both surfaces. Env vars (SENTRY_RELEASE / APP_VERSION) still win if set.

export const EDGE_RELEASE = "${sha}";
export const EDGE_RELEASE_STAMPED_AT = "${stampedAt}";
`;
}

function readCurrent() {
  try {
    return readFileSync(TARGET, "utf8");
  } catch {
    return "";
  }
}

function extractSha(contents) {
  const m = contents.match(/EDGE_RELEASE\s*=\s*"([^"]+)"/);
  return m ? m[1] : "";
}

const sha = currentSha();
if (!sha) {
  console.error("[stamp-edge-release] git rev-parse failed — is this a git checkout?");
  process.exit(CHECK_ONLY ? 1 : 0); // in write mode: soft-fail, keep existing stamp
}

const existing = readCurrent();
const existingSha = extractSha(existing);

if (existingSha === sha) {
  if (!CHECK_ONLY) console.log(`[stamp-edge-release] up to date (${sha})`);
  process.exit(0);
}

if (CHECK_ONLY) {
  console.error(
    `[stamp-edge-release] OUT OF DATE: release.ts has "${existingSha || "(none)"}" but HEAD is "${sha}".`,
  );
  console.error("  → Run: npm run stamp:release && git add supabase/functions/_shared/release.ts");
  process.exit(1);
}

const next = render(sha, new Date().toISOString());
writeFileSync(TARGET, next, "utf8");
console.log(`[stamp-edge-release] wrote ${sha} → supabase/functions/_shared/release.ts`);
