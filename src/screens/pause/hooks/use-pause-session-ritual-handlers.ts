import { useCallback } from 'react';
import { usePauseFavoriteToggle } from '@/screens/pause/hooks/use-pause-favorite-toggle';
import { usePauseShiftFrameDoneHandler } from '@/screens/pause/hooks/use-pause-shift-frame-done-handler';
import { usePauseSessionMoodAndPersist } from '@/screens/pause/hooks/use-pause-session-mood-and-persist';
import { usePauseSessionScaffoldPresentation } from '@/screens/pause/hooks/use-pause-session-scaffold-presentation';
import { usePauseSessionBreathHandlers } from '@/screens/pause/hooks/use-pause-session-breath-handlers';
import { usePauseSessionReflectAndDecide } from '@/screens/pause/hooks/use-pause-session-reflect-and-decide';
import type { usePauseSessionProviders } from '@/screens/pause/hooks/use-pause-session-providers';
import type { usePauseSessionShellRitual } from '@/screens/pause/hooks/use-pause-session-shell-ritual';

type PauseSessionProviders = ReturnType<typeof usePauseSessionProviders>;
type PauseSessionShellRitual = ReturnType<typeof usePauseSessionShellRitual>;

/** Mood, breath, reflect/decide, scaffold, and chrome handlers after shell + ritual are ready. */
export function usePauseSessionRitualHandlers(
  p: PauseSessionProviders,
  { shell, ritual }: PauseSessionShellRitual,
) {
  const {
    t,
    handleReturn,
    mantra,
    dismissMessage,
    btcData,
    trackedAssetId,
    subscribed,
    subLoading,
    requirePro,
    refreshSubscription,
    prefersReducedMotion,
    breathSecondLabelVariant,
  } = p;

  const {
    restored,
    hydration,
    fetchedInstance,
    fetchFailed,
    waitingForFetch,
    message,
    context,
    pauseInstanceId,
    companions,
    companionPrefs,
    severity,
    pauseInstanceIdForTerminal,
    pending,
    leaveWithPendingOpen,
    setLeaveWithPendingOpen,
    leaveSheetBusy,
    confirmLeavePauseSession,
    requestExitPauseBeforeDone,
    handleDeclinePendingFromLeaveSheet,
    handlePendingAdoptFromLeaveSheet,
    hasCoalescedShellSession,
  } = shell;

  const {
    step,
    setStep,
    phase,
    setPhase,
    decision,
    setDecision,
    isFavorite,
    setIsFavorite,
    moodDone,
    setMoodDone,
    moodAfterDone,
    setMoodAfterDone,
    selectedMood,
    setSelectedMood,
    selectedMoodAfter,
    setSelectedMoodAfter,
    feelIntensity,
    setFeelIntensity,
    shiftIntensity,
    setShiftIntensity,
    breathingFirstCompleted,
    setBreathingFirstCompleted,
    breathingSecondCompleted,
    setBreathingSecondCompleted,
    frameDone,
    setFrameDone,
    curtainLifted,
    pauseImpactData,
    setPauseImpactData,
    ritualEntry,
    setRitualEntry,
    briefStep,
    setBriefStep,
    briefIntegrateDone,
    setBriefIntegrateDone,
    selectedBriefFace,
    setSelectedBriefFace,
    swipeDirection,
    setSwipeDirection,
    soundMuted,
    setSoundMuted,
  } = ritual;

  const { toggleFavorite } = usePauseFavoriteToggle({
    pauseInstanceId,
    isFavorite,
    setIsFavorite,
    subscribed,
    t,
  });

  const handlePauseSessionChromeClose = useCallback(() => {
    if (phase === 'done') {
      handleReturn();
    } else {
      requestExitPauseBeforeDone();
    }
  }, [phase, handleReturn, requestExitPauseBeforeDone]);

  const {
    lastShiftLogKeyRef,
    depthPickerOnBrief,
    handleDepthPickerDeep,
    onFeelTilesSelect,
  } = usePauseSessionMoodAndPersist({
    pauseInstanceId,
    t,
    requirePro,
    ritualEntry,
    message,
    context,
    companions,
    companionPrefs,
    severity,
    moodDone,
    moodAfterDone,
    selectedMood,
    selectedMoodAfter,
    feelIntensity,
    shiftIntensity,
    phase,
    decision,
    step,
    breathingFirstCompleted,
    breathingSecondCompleted,
    frameDone,
    briefStep,
    briefIntegrateDone,
    selectedBriefFace,
    setRitualEntry,
    setBriefStep,
    setBriefIntegrateDone,
    setSelectedBriefFace,
    setMoodDone,
    setSelectedMood,
    setFeelIntensity,
  });

  const breath = usePauseSessionBreathHandlers({
    pauseInstanceId,
    restored,
    t,
    subLoading,
    subscribed,
    requirePro,
    phase,
    ritualEntry,
    briefStep,
    step,
    breathingFirstCompleted,
    breathingSecondCompleted,
    setSwipeDirection,
    setStep,
    setBriefStep,
    setBriefIntegrateDone,
    setBreathingFirstCompleted,
    setBreathingSecondCompleted,
    setRitualEntry,
    setFrameDone,
    setMoodAfterDone,
  });

  const { handleFrameImDone } = usePauseShiftFrameDoneHandler({
    pauseInstanceId,
    t,
    lastShiftLogKeyRef,
    setFrameDone,
    setMoodAfterDone,
    goToStep: breath.goToStep,
  });

  const reflect = usePauseSessionReflectAndDecide({
    t,
    ritualEntry,
    step,
    pauseInstanceId,
    context,
    message,
    btcData,
    companionsHaiku: companions.haiku ?? null,
    dismissMessage,
    refreshSubscription,
    setDecision,
    setPauseImpactData,
    setPhase,
    selectedMood,
    selectedMoodAfter,
    breathingFirstCompleted,
    breathingSecondCompleted,
    feelIntensity,
    shiftIntensity,
  });

  const scaffold = usePauseSessionScaffoldPresentation({
    t,
    btcData,
    trackedAssetId,
    ritualEntry,
    phase,
    hasCoalescedShellSession,
    fetchedInstance,
    swipeDirection,
    prefersReducedMotion,
    briefStep,
    step,
    moodDone,
    selectedMood,
    selectedBriefFace,
    feelIntensity,
    onFeelTilesSelect,
    setBriefStep,
    breathingRef: breath.breathingRef,
    mantra,
    severity,
    breathingFirstCompleted,
    breathingSecondCompleted,
    setBreathTimedActive: breath.trackBreathTimedActive,
    setBreathingFirstCompleted,
    setBreathingSecondCompleted,
    handleBriefBreathContinue: breath.handleBriefBreathContinue,
    handleBriefSkipBreath: breath.handleBriefSkipBreath,
    soundMuted,
    briefIntegrateDone,
    handleBriefIntegrateComplete: breath.handleBriefIntegrateComplete,
    handleBriefRepeatBreaths: breath.handleBriefRepeatBreaths,
    handleBriefSwitchToDeepPause: breath.handleBriefSwitchToDeepPause,
    handleDecide: reflect.handleDecide,
    goToStep: breath.goToStep,
    handleContinueAfterFirstBreath: breath.handleContinueAfterFirstBreath,
    handleContinueAfterSecondBreath: breath.handleContinueAfterSecondBreath,
    handleSkipFirstBreath: breath.handleSkipFirstBreath,
    handleSkipSecondBreath: breath.handleSkipSecondBreath,
    prefersReducedMotion,
    companions,
    companionPrefs,
    pauseInstanceId,
    context,
    message: reflect.effectiveReflectionMessage,
    isFavorite,
    toggleFavorite,
    subscribed,
    handleFrameImDone,
    handleDeepFirstBreathRepeat: breath.handleDeepFirstBreathRepeat,
    handleDeepSecondBreathRepeat: breath.handleDeepSecondBreathRepeat,
    severityAbsPct: Math.abs(btcData?.changePercent ?? 0),
    reflectionLoading: reflect.reflectionLoading,
    reflectionError: reflect.reflectionError,
    onReflectionRetry: reflect.retryReflection,
  });

  return {
    handleReturn,
    leaveWithPendingOpen,
    setLeaveWithPendingOpen,
    pending,
    leaveSheetBusy,
    confirmLeavePauseSession,
    setRitualEntry,
    setBriefStep,
    setStep,
    handlePendingAdoptFromLeaveSheet,
    handleDeclinePendingFromLeaveSheet,
    hasCoalescedShellSession,
    phase,
    waitingForFetch,
    fetchFailed,
    hydration,
    sessionOnPicker: scaffold.sessionOnPicker,
    depthContextLine: scaffold.depthContextLine,
    depthPickerOnBrief,
    handleDepthPickerDeep,
    subscribed,
    requestExitPauseBeforeDone,
    scaffoldRitualDerived: scaffold.scaffoldRitualDerived,
    engagedOpenMaxCountdownSlot: scaffold.engagedOpenMaxCountdownSlot,
    curtainLifted,
    prefersReducedMotion,
    handlePauseSessionChromeClose,
    step,
    handlePauseHeaderBack: breath.handlePauseHeaderBack,
    showPauseHeaderBack: breath.showPauseHeaderBack,
    briefStepperSlot: scaffold.briefStepperSlot,
    breathSecondLabelVariant,
    soundMuted,
    setSoundMuted,
    ritualEntry,
    briefRitual: scaffold.briefRitual,
    deepRitual: scaffold.deepRitual,
    decision,
    pauseImpactData,
    pauseInstanceIdForTerminal,
  };
}
