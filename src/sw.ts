/// <reference lib="webworker" />
import { precacheAndRoute } from "workbox-precaching";
import { registerRoute } from "workbox-routing";
import { NetworkFirst } from "workbox-strategies";
import { ExpirationPlugin } from "workbox-expiration";

declare const self: ServiceWorkerGlobalScope;

// Listen for skip-waiting message from the client
self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") {
    self.skipWaiting();
  }
});

// Claim clients on activate
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

// Precache all assets generated by the build
precacheAndRoute(self.__WB_MANIFEST);

// Navigation requests: always try network first so a stale precache
// can never cause a permanent white screen after a deploy.
registerRoute(
  ({ request }) => request.mode === "navigate",
  new NetworkFirst({
    cacheName: "html-nav",
    plugins: [
      new ExpirationPlugin({ maxEntries: 5, maxAgeSeconds: 86400 }),
    ],
  })
);

// Runtime caching for CoinGecko API
registerRoute(
  ({ url }) => url.origin === "https://api.coingecko.com",
  new NetworkFirst({
    cacheName: "btc-data",
    plugins: [
      new ExpirationPlugin({ maxEntries: 5, maxAgeSeconds: 300 }),
    ],
  })
);

// Push notification handler
self.addEventListener("push", (event) => {
  const data = event.data?.json() ?? {};
  const title = data.title || "Holzen";

  // Build deep-link URL: navigate to Home with pause=ready flag
  const baseUrl = self.registration.scope.replace(/\/$/, "");
  const targetUrl = data.action === "pause_ready"
    ? `${baseUrl}/?pause=ready`
    : baseUrl;

  const options = {
    body: data.body || "A moment to pause.",
    icon: "/icon-512.png",
    badge: "/icon-512.png",
    tag: `holzen-${data.pauseInstanceId || Date.now()}`,
    renotify: true,
    data: {
      url: targetUrl,
      pauseInstanceId: data.pauseInstanceId ?? null,
    },
  } as NotificationOptions & { renotify: boolean };

  event.waitUntil(self.registration.showNotification(title, options));
});

// Open app when notification is tapped
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || self.registration.scope;

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clients) => {
      for (const client of clients) {
        if (new URL(client.url).origin === new URL(targetUrl).origin && "focus" in client) {
          return client.focus();
        }
      }
      return self.clients.openWindow(targetUrl);
    })
  );
});
